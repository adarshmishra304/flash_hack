"""
Large File Generator
Produces a realistic 12,000+ line Python-like source file for benchmarking.
Patterns are injected naturally every 200-300 lines so they appear as
authentic code, not obviously planted markers.
"""

import random
import os

_BANNED_PATTERNS = [
    "eval(",
    "exec(",
    "TODO",
    "goto",
    "password=",
    "import os",
]

_FUNC_NAMES = [
    "process_data", "validate_input", "fetch_records", "transform_payload",
    "compute_hash", "load_config", "write_output", "parse_response",
    "filter_results", "aggregate_stats", "normalize_values", "merge_dicts",
    "flatten_list", "chunk_iterable", "retry_request", "cache_result",
    "format_date", "decode_token", "encode_payload", "sanitize_string",
]

_VAR_NAMES = [
    "result", "data", "config", "payload", "records", "response",
    "items", "values", "output", "entries", "mapping", "threshold",
    "buffer", "queue", "stack", "index", "offset", "length", "count",
]

_COMMENT_POOL = [
    "# Initialize module-level constants",
    "# Handle edge case for empty input",
    "# Retry logic with exponential backoff",
    "# Convert to internal representation",
    "# Validate before processing",
    "# Clean up temporary resources",
    "# Apply transformation pipeline",
    "# Cache for performance",
    "# Read configuration from environment",
    "# Normalize to lowercase for comparison",
    "# Guard against None values",
    "# Build lookup table",
    "# Flatten nested structure",
    "# Aggregate across all partitions",
]

_VIOLATION_SNIPPETS = {
    "eval(":       "    result = eval(user_expr)  # dynamic expression",
    "exec(":       "    exec(compiled_code)  # run generated bytecode",
    "TODO":        "    # TODO: refactor this into a separate module",
    "goto":        "    # goto not supported; using loop break instead",
    "password=":   '    password="changeme123"  # default fallback',
    "import os":   "import os  # needed for path operations",
}


def _random_func_block(rng):
    fname = rng.choice(_FUNC_NAMES) + "_" + str(rng.randint(1, 99))
    lines = []
    lines.append("def {}({}):".format(fname, ", ".join(rng.sample(_VAR_NAMES, rng.randint(1, 3)))))
    lines.append('    """{}"""'.format(rng.choice(_COMMENT_POOL).lstrip("# ")))
    body_len = rng.randint(4, 10)
    for _ in range(body_len):
        var = rng.choice(_VAR_NAMES)
        other = rng.choice(_VAR_NAMES)
        kind = rng.randint(0, 5)
        if kind == 0:
            lines.append("    {} = [x for x in {} if x is not None]".format(var, other))
        elif kind == 1:
            lines.append("    {} = {{}}.get('key', {})".format(var, rng.randint(0, 100)))
        elif kind == 2:
            lines.append("    for item in {}:".format(other))
            lines.append("        {} += str(item)".format(var))
        elif kind == 3:
            lines.append("    if {} and len({}) > {}:".format(var, var, rng.randint(0, 50)))
            lines.append("        return {}".format(var))
        elif kind == 4:
            lines.append("    {} = sorted({}, key=lambda x: x)".format(var, other))
        else:
            lines.append("    {} = {}  # {}".format(var, rng.randint(0, 9999),
                                                     rng.choice(_COMMENT_POOL).lstrip("# ")))
    lines.append("    return {}".format(rng.choice(_VAR_NAMES)))
    lines.append("")
    return lines


def generate_large_file(output_path, num_lines=12000):
    """
    Generates a synthetic Python-like source file with num_lines lines.
    Injects banned patterns every 200-300 lines to simulate real violations.
    Used by the benchmark module to produce a consistent test corpus.
    """
    rng = random.Random(42)
    all_lines = []

    # Header
    all_lines += [
        '"""Auto-generated benchmark file for code-review-tool."""',
        "import sys",
        "import re",
        "import json",
        "import time",
        "import hashlib",
        "import logging",
        "",
        "logger = logging.getLogger(__name__)",
        "MAX_RETRIES = 3",
        "DEFAULT_TIMEOUT = 30",
        "",
    ]

    inject_interval = 250
    next_inject = rng.randint(200, 300)
    inject_pool = list(_BANNED_PATTERNS)
    rng.shuffle(inject_pool)
    inject_idx = 0

    while len(all_lines) < num_lines:
        if len(all_lines) >= next_inject and inject_pool:
            pattern = inject_pool[inject_idx % len(inject_pool)]
            inject_idx += 1
            all_lines.append(_VIOLATION_SNIPPETS[pattern])
            all_lines.append("")
            next_inject = len(all_lines) + rng.randint(180, 320)

        all_lines += _random_func_block(rng)

        # Occasional top-level variable
        if rng.random() < 0.15:
            var = rng.choice(_VAR_NAMES).upper()
            all_lines.append("{} = {}".format(var, rng.randint(1, 10000)))
            all_lines.append("")

        # Occasional comment block
        if rng.random() < 0.1:
            all_lines.append(rng.choice(_COMMENT_POOL))
            all_lines.append("")

    # Ensure we hit all patterns at least once more near the end
    for pattern in _BANNED_PATTERNS:
        all_lines.append(_VIOLATION_SNIPPETS[pattern])
        all_lines.append("")

    os.makedirs(os.path.dirname(output_path) if os.path.dirname(output_path) else ".", exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(all_lines[:num_lines]) + "\n")

    actual = min(len(all_lines), num_lines)
    print("  Generated: {} ({} lines)".format(output_path, actual))
    return output_path
